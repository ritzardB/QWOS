BEGIN;

-- -----------------------------------------------------------------------------
-- ULID
-- -----------------------------------------------------------------------------

CREATE DOMAIN ulid AS CHAR(26)
CHECK (
    VALUE ~ '^[0-9A-HJKMNP-TV-Z]{26}$'
);

-- -----------------------------------------------------------------------------
-- Email Address
-- -----------------------------------------------------------------------------

CREATE DOMAIN email_address AS CITEXT
CHECK (
    VALUE ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
);

-- -----------------------------------------------------------------------------
-- Person Name
-- -----------------------------------------------------------------------------

CREATE DOMAIN person_name AS VARCHAR(100)
CHECK (
    LENGTH(TRIM(VALUE)) > 0
);

-- -----------------------------------------------------------------------------
-- Display Name
-- -----------------------------------------------------------------------------

CREATE DOMAIN display_name_text AS VARCHAR(150)
CHECK (
    LENGTH(TRIM(VALUE)) > 0
);

-- -----------------------------------------------------------------------------
-- Identifier Code
-- -----------------------------------------------------------------------------

CREATE DOMAIN identifier_code AS VARCHAR(50)
CHECK (
    VALUE ~ '^[a-z][a-z0-9_]{1,49}$'
);

-- -----------------------------------------------------------------------------
-- Description
-- -----------------------------------------------------------------------------

CREATE DOMAIN description_text AS TEXT;

-- -----------------------------------------------------------------------------
-- User Agent
-- -----------------------------------------------------------------------------

CREATE DOMAIN user_agent_text AS TEXT;

-- -----------------------------------------------------------------------------
-- IP Address
-- -----------------------------------------------------------------------------

CREATE DOMAIN ip_address AS INET;

-- -----------------------------------------------------------------------------
-- Token Hash
-- -----------------------------------------------------------------------------
CREATE DOMAIN token_hash AS TEXT
CHECK (
    LENGTH(TRIM(VALUE)) >= 32
);

-- -----------------------------------------------------------------------------
-- Expiration Timestamp
-- -----------------------------------------------------------------------------
CREATE DOMAIN expiration_timestamp AS TIMESTAMPTZ;



COMMIT;